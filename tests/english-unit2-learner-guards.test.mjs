test('Unit 2 write guard rejects foreign scope, stale items, broad actions and arbitrary cancellations',()=>{
 assert.equal(designated.length,2);assert.equal(a.unitId,english.unitId);
 assert.equal(allowed('start-learning-session',{...selection(a),mode:'diagnostic'}),true);
 assert.equal(allowed('start-learning-session',{...selection(b),mode:'diagnostic'}),false);
 assert.equal(allowed('start-learning-session',{...selection(a),unitId:'3ef44139-0053-58e6-ab0d-5901a0213683',mode:'diagnostic'}),false);
 assert.equal(allowed('start-learning-session',{...selection(a),mode:'mastery_check'}),false);
 const body={sessionId:current.id,sessionItemId:current.sessionItemId,itemId:current.itemId,response:{value:'A'}};
 assert.equal(allowed('submit-answer',body),true);
 for(const field of ['sessionId','sessionItemId','itemId'])assert.equal(allowed('submit-answer',{...body,[field]:ledger.workId}),false);
 assert.equal(allowed('submit-mastery-answer',body),false);
 assert.equal(allowed('submit-answer',body,'B_student'),false);
 assert.equal(allowed('manage-written-work',{action:'submit',context:selection(a),payload:{taskId:writingTask.id}}),true);
 assert.equal(allowed('manage-written-work',{action:'submit',context:selection(b),payload:{taskId:writingTask.id}}),false);
 assert.equal(allowed('manage-written-work',{action:'review',context:{assignmentId:a.teacherAssignmentId,curriculumReleaseId:a.curriculumReleaseId,unitId:a.unitId},payload:{workId:ledger.workId}},'A_teacher'),true);
 assert.equal(allowed('manage-student-invitation',{action:'create_code'},'A_teacher'),false);
 const cancel={sessionId:current.id,sessionItemId:current.sessionItemId,action:'cancel'};
 assert.equal(allowed('get-learning-audio',cancel),false);
 const technical={...current,mode:'mastery_check',intent:'technical_exit'};
 assert.equal(allowed('get-learning-audio',cancel,'A_student',technical),false);
 assert.equal(allowed('get-learning-audio',cancel,'A_student',{...technical,faultInjected:true}),true);
 assert.equal(allowed('get-learning-audio',{...cancel,sessionItemId:ledger.workId},'A_student',{...technical,faultInjected:true}),false);
});
test('private answer mapper verifies prompt and shuffled choice fingerprint, with explicit failure only',()=>{
 assert.deepEqual(syntheticResponse(item,source),{value:'D'});
 assert.deepEqual(syntheticResponse(item,source,true),{value:'A'});
 assert.throws(()=>syntheticResponse({...item,promptHy:'modified'},source));
 assert.throws(()=>syntheticResponse({...item,options:[item.options[1]]},source));
 assert.throws(()=>syntheticResponse({...item,options:[item.options[0],{...item.options[0],option_key:'B'}]},source));
 assert.throws(()=>syntheticResponse(item));
 const typed={type:'typed_fields',promptSha256:sha('fixture prompt'),response:{schemaVersion:'fixture-v1',fields:{f:'test'}}};
 assert.deepEqual(syntheticResponse({...item,type:'typed_fields'},typed),typed.response);
 assert.throws(()=>syntheticResponse({...item,type:'typed_fields'},typed,true));
});
test('private fixture is bounded and rejects tampered bytes, foreign scope and missing identities',()=>{
 const fixture={schemaVersion:'haiedu-english-unit2-private-responses-v1',scope:english,items:{[item.id]:source}};
 const encode=value=>{const raw=Buffer.from(JSON.stringify(value));return {encoded:gzipSync(raw).toString('base64'),manifest:{...contract,responseFixture:{...contract.responseFixture,itemCount:1,sha256:sha(raw)}}};};
 const good=encode(fixture);assert.equal(loadResponseFixture(good.encoded,good.manifest).size,1);
 assert.throws(()=>loadResponseFixture(good.encoded,contract));
 const foreign=encode({...fixture,scope:{...english,unitId:b.schoolId}});assert.throws(()=>loadResponseFixture(foreign.encoded,foreign.manifest));
 const invalid=encode({...fixture,items:{invalid:source}});assert.throws(()=>loadResponseFixture(invalid.encoded,invalid.manifest));
 assert.throws(()=>loadResponseFixture('A'.repeat(48001),good.manifest));
 assert.throws(()=>loadResponseFixture('not/base64?!',good.manifest));
});
test('continuation accepts only owned finite forms and cannot resume an unexpected start',()=>{
 const report={schemaVersion:'haiedu-english-unit2-learner-qa-v1',workflowRunId:'123',scope:english,studentId:a.studentId,status:'failed',responseFixtureSha256:contract.responseFixture.sha256,sessions:[current],workId:null};
 assert.equal(validResume(report,'123'),true);
 for(const changed of [{workflowRunId:'124'},{status:'passed'},{studentId:b.studentId},{responseFixtureSha256:'0'.repeat(64)},{unexpectedSessionId:ledger.workId},{sessions:[current,current]}])assert.equal(validResume({...report,...changed},'123'),false);
 const tech={...current,id:ledger.workId,mode:'mastery_check',intent:'technical_exit',status:'technical_unscored'};
 assert.equal(validResume({...report,sessions:[current,tech]},'123'),true);
 assert.equal(validResume({...report,sessions:[current,tech,{...tech,id:current.itemId}]},'123'),false);
 assert.equal(validResume({...report,sessions:[{...current,intent:'passed'}]},'123'),false);
 assert.equal(validResume({...report,sessions:[{...current,answered:25}]},'123'),false);
});
