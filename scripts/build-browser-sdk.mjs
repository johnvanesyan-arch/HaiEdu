import { build } from 'esbuild';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = 'web/supabase-browser.bundle.mjs';

export function assertLocalBrowserImports(outputs) {
  for (const file of Object.values(outputs)) {
    for (const dependency of file.imports) {
      const local = /^(?:\.\.?\/|\/(?!\/))/.test(dependency.path);
      const canonicalSdk = file.entryPoint === 'web/supabase-browser.mjs'
        && dependency.path === '@supabase/supabase-js';
      if (!local && !canonicalSdk) {
        throw new Error(`External browser dependency in ${file.entryPoint}: ${dependency.path}`);
      }
    }
  }
}

export async function buildBrowserSdk({ check = false } = {}) {
  const result = await build({
    absWorkingDir: root, entryPoints: ['web/supabase-browser.mjs'], outfile: output,
    bundle: true, format: 'esm', platform: 'browser', target: 'es2022',
    minify: true, charset: 'utf8', write: false, legalComments: 'eof', metafile: true,
    banner: { js: '// Generated by scripts/build-browser-sdk.mjs; edit the canonical source and pinned lockfile.' },
  });
  if (Object.values(result.metafile.outputs).some(file => file.imports.length)) {
    throw new Error('The pinned browser SDK must be self-contained.');
  }
  const bytes = Buffer.from(result.outputFiles[0].contents);
  if (check) {
    if (!bytes.equals(await readFile(resolve(root, output)))) {
      throw new Error(`${output} is stale; run npm run build:browser-sdk.`);
    }
    // Parse every browser module, including literal dynamic imports. URLs in
    // comments and API fetches are not dependency imports.
    const entries = (await readdir(resolve(root, 'web'), { recursive: true }))
      .filter(name => /\.(?:m?js)$/.test(name)).map(name => `web/${name}`);
    const graph = await build({ absWorkingDir: root, entryPoints: entries,
      outdir: '.unused-browser-dependency-check', bundle: false, format: 'esm',
      platform: 'browser', write: false, metafile: true, logLevel: 'silent' });
    assertLocalBrowserImports(graph.metafile.outputs);
  } else {
    await writeFile(resolve(root, output), bytes);
  }
  return { bytes: bytes.length, inputs: Object.keys(result.metafile.inputs) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const result = await buildBrowserSdk({ check });
  console.log(`Pinned browser SDK ${check ? 'matches canonical sources' : 'built'} (${result.bytes} bytes).`);
}
