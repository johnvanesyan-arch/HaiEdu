import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
const output='web/teacher-dependencies.bundle.mjs';
const result=await build({entryPoints:['web/teacher-dependencies.mjs'],outfile:output,bundle:true,format:'esm',platform:'browser',target:'es2022',minify:true,charset:'utf8',write:false,legalComments:'eof',banner:{js:'// Generated by scripts/build-teacher-entry.mjs; edit the canonical source modules.'}});
const bytes=result.outputFiles[0].contents;
if(process.argv.includes('--check')){
 const current=await readFile(output);if(!current.equals(Buffer.from(bytes)))throw Error('Teacher startup bundle is stale; run npm run build:teacher.');
 console.log('Teacher startup bundle matches canonical sources.');
}else{await writeFile(output,bytes);console.log('Teacher startup dependencies bundled.');}
